/// <summary>
/// Tipos de cofre.
///  Pequeno → mayormente comunes (como el cofre pequeño de RoR2).
///  Grande  → poco comunes o mejores.
///  Jefe    → lo sueltan los jefes, garantiza buena rareza.
///  Equipo  → solo objetos activos.
///  Maldito → solo objetos malditos (con desventaja).
/// </summary>
public enum ChestTier
{
	Pequeno = 0,
	Grande = 1,
	Jefe = 2,
	Equipo = 3,
	Maldito = 4,
}
